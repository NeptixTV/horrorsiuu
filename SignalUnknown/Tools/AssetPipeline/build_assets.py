"""Builds every game asset from the downloaded source models.

    python3 build_assets.py <downloads> <work dir> [project dir]

<downloads> must contain the unpacked source models:
    forest/scene.gltf     "a forest (3) with a road at night for game" by dasy444            CC-BY-4.0
    wendigo/scene.gltf    "Wendigo" by DannyAg                                             CC-BY-4.0
    house/scene.gltf      "Modular Kit Horror House 1" by Pieter Ferreira                  CC-BY-4.0
    cyclops/cyclops.glb   "Lesser Cyclops Variant Rig" by DM-913                           CC-BY-4.0
    egypt/scene.gltf      "Egypt chamber for AR / VR games" by arloopa (optional)          Sketchfab Standard

Intermediate .glb files go to <work dir>. The game files (.sumodel) go to <project>/Content/SUModels and the
layout of the manor site is written to Source/SignalUnknown/Logic/SUManorData.h.
"""
import json
import os
import sys
import numpy as np
import build_vegetation
import build_wendigo
import build_cyclops
import build_house
import pack

HERE = os.path.dirname(os.path.abspath(__file__))


def ue(p):
    return (float(p[2]) * 100.0, -float(p[0]) * 100.0, float(p[1]) * 100.0)


def fmt(v):
    return '{%.1ff, %.1ff, %.1ff}' % v


def write_header(path, manor, pts, tomb_manifest, tomb_pts, speeds):
    L = []
    A = L.append
    A('// SIGNAL UNKNOWN - layout of the manor site and everything below it.')
    A('// GENERATED by Tools/AssetPipeline/build_assets.py - do not edit by hand.')
    A('// Unreal units (cm), relative to the site origin (ground in front of the manor door); the door faces +X, the house lies towards -X.')
    A('#pragma once')
    A('')
    A('namespace SUManor')
    A('{')
    A('\tstruct Vec { float X, Y, Z; };')
    A('\tstruct Anchor { const char* Name; Vec P; };')
    A('\tstruct Light { const char* Id; Vec P; float Radius; float Intensity; float R, G, B; int Kind; int Flicker; bool bPowered; };')
    A('\tstruct Door { const char* Id; Vec P; float DirX, DirY; float Width, Height; int Kind; const char* Lock; };')
    A('\tstruct Zone { const char* Name; Vec Lo, Hi; };')
    A('\tstruct Edge { int A, B; };')
    A('\tstruct Hide { Vec Entry, Inside; };')
    A('')
    anchors = dict(pts['anchors'])
    anchors.update(tomb_pts['anchors'])
    A('\tinline constexpr Anchor Anchors[] = {')
    for k in sorted(anchors):
        A('\t\t{"%s", %s},' % (k, fmt(ue(anchors[k]))))
    A('\t};')
    kinds = {'none': 0, 'bulb': 1, 'lantern': 2}
    for name, lights in (('Lights', pts['lights']), ('TombLights', tomb_pts['lights'])):
        A('\tinline constexpr Light %s[] = {' % name)
        for l in lights:
            A('\t\t{"%s", %s, %.1ff, %.3ff, %.2ff, %.2ff, %.2ff, %d, %d, %s},' % (l['id'], fmt(ue(l['pos'])), l['radius'] * 100.0, l['intensity'], *l['color'],
                                                                         kinds[l['kind']], l['flicker'], 'true' if l['powered'] else 'false'))
        A('\t};')
    dk = {'none': 0, 'single': 1, 'double': 2}
    A('\tinline constexpr Door Doors[] = {')
    for d in pts['doors']:
        dx, dz = d['dir']
        A('\t\t{"%s", %s, %.1ff, %.1ff, %.1ff, %.1ff, %d, "%s"},' % (d['id'], fmt(ue(d['pos'])), float(dz), -float(dx), d['width'] * 100.0, d['height'] * 100.0, dk[d['kind']], d['lock']))
    A('\t};')
    zones = dict(pts['zones'])
    zones['Tomb'] = tomb_pts['zone']
    A('\tinline constexpr Zone Zones[] = {')
    for k, z in zones.items():
        a, b = np.array(ue(z['lo'])), np.array(ue(z['hi']))
        A('\t\t{"%s", %s, %s},' % (k, fmt(tuple(np.minimum(a, b))), fmt(tuple(np.maximum(a, b)))))
    A('\t};')
    nodes = list(pts['nav_nodes'])
    edges = list(pts['nav_edges'])
    first_tomb = len(nodes)
    prev = pts['nav_exit']
    for p in tomb_pts['nav']:
        nodes.append(p)
        edges.append((prev, len(nodes) - 1))
        prev = len(nodes) - 1
    A('\tinline constexpr Vec NavNodes[] = {')
    for p in nodes:
        A('\t\t%s,' % fmt(ue(p)))
    A('\t};')
    A('\tinline constexpr Edge NavEdges[] = {' + ', '.join('{%d, %d}' % e for e in edges) + '};')
    A('\tinline constexpr int NavFirstTombNode = %d;   // nodes from here on only exist when the tomb is present' % first_tomb)
    A('\tinline constexpr Hide Hides[] = {')
    for h in pts['hides']:
        A('\t\t{%s, %s},' % (fmt(ue(h['entry'])), fmt(ue(h['pos']))))
    A('\t};')
    A('\tinline constexpr Vec TombCubes[] = {' + ', '.join(fmt(ue(c)) for c in tomb_pts['cubes']) + '};')
    A('\tinline constexpr Vec TombDoorPos = %s;' % fmt(ue(tomb_pts['door']['pos'])))
    A('\tinline constexpr Vec CyclopsSpawn = %s;' % fmt(ue(pts['spawns']['Cyclops'])))
    c, r = pts['pad']['centre'], pts['pad']['radius']
    A('\tinline constexpr Vec PadCentre = %s;' % fmt(ue(c)))
    A('\tinline constexpr float PadRadius = %.1ff;' % (r * 100.0))
    s = pts['shaft']
    a, b = np.array(ue((s['x0'], 0, s['z0']))), np.array(ue((s['x1'], 0, s['z1'])))
    A('\t// footprint of the cellar stair shaft: the terrain needs a hole here')
    A('\tinline constexpr float ShaftMinX = %.1ff, ShaftMaxX = %.1ff, ShaftMinY = %.1ff, ShaftMaxY = %.1ff;' % (min(a[0], b[0]), max(a[0], b[0]), min(a[1], b[1]), max(a[1], b[1])))
    for name, group in (('ManorMeshes', 'manor'), ('UndergroundMeshes', 'underground')):
        A('\tinline constexpr const char* %s[] = {%s};' % (name, ', '.join('"%s"' % k for k, v in manor.items() if v['group'] == group)))
    A('\tinline constexpr const char* TombMeshes[] = {%s};' % ', '.join('"%s"' % k for k in tomb_manifest if 'Cube' not in k and 'Door' not in k))
    for k, v in speeds.items():
        A('\tinline constexpr float %s = %.1ff;' % (k, v))
    A('}')
    A('')
    with open(path, 'w', encoding='utf-8-sig', newline='\r\n') as f:
        f.write('\n'.join(L))


def main(src, work, project=None):
    project = project or os.path.abspath(os.path.join(HERE, '..', '..'))
    models = os.path.join(project, 'Content', 'SUModels')
    restricted = os.path.join(models, 'Restricted')
    os.makedirs(work, exist_ok=True)
    os.makedirs(restricted, exist_ok=True)
    manifest = {}
    manifest.update(build_vegetation.build(os.path.join(src, 'forest'), work))
    wend = build_wendigo.build(os.path.join(src, 'wendigo'), work)
    cyc = build_cyclops.build(os.path.join(src, 'cyclops', 'cyclops.glb'), work)
    manifest.update(wend)
    manifest.update(cyc)
    has_tomb = os.path.exists(os.path.join(src, 'egypt', 'scene.gltf'))
    manor, pts = build_house.build(os.path.join(src, 'house'), work, with_tomb_chamber=True)
    manifest.update(manor)
    sizes = {}
    sizes['Vegetation'] = pack.pack(os.path.join(work, 'Vegetation.glb'), os.path.join(models, 'Vegetation.sumodel'))
    w, c = wend['SK_Wendigo'], cyc['SK_Cyclops']
    sizes['Wendigo'] = pack.pack(os.path.join(work, 'SK_Wendigo.glb'), os.path.join(models, 'Wendigo.sumodel'),
                                 {'WalkSpeed': w['walk_speed_mps'] * 100, 'RunSpeed': w['run_speed_mps'] * 100, '_loops': {'Attack': False, 'Scream': False}},
                                 roughness_override=0.62)
    sizes['Cyclops'] = pack.pack(os.path.join(work, 'SK_Cyclops.glb'), os.path.join(models, 'Cyclops.sumodel'),
                                 {'WalkSpeed': c['walk_speed_mps'] * 100, 'RunSpeed': c['run_speed_mps'] * 100, '_loops': {'Attack': False, 'Scream': False}},
                                 roughness_override=0.58)
    sizes['Manor'] = pack.pack(os.path.join(work, 'Manor.glb'), os.path.join(models, 'Manor.sumodel'))
    tomb_manifest, tomb_pts = {}, None
    if has_tomb:
        import build_tomb
        rwork = os.path.join(work, 'restricted')
        os.makedirs(rwork, exist_ok=True)
        tomb_manifest, tomb_pts = build_tomb.build(os.path.join(src, 'egypt'), rwork)
        sizes['Tomb'] = pack.pack(os.path.join(rwork, 'Tomb.glb'), os.path.join(restricted, 'Tomb.sumodel'), max_texture=1024)
        json.dump({'manifest': tomb_manifest, 'points': tomb_pts}, open(os.path.join(HERE, 'tomb_layout.json'), 'w'), indent=1)
    else:
        saved = json.load(open(os.path.join(HERE, 'tomb_layout.json')))      # positions only, no model data
        tomb_manifest, tomb_pts = saved['manifest'], saved['points']
    speeds = {'WendigoWalkSpeed': w['walk_speed_mps'] * 100, 'WendigoRunSpeed': w['run_speed_mps'] * 100,
              'CyclopsWalkSpeed': c['walk_speed_mps'] * 100, 'CyclopsRunSpeed': c['run_speed_mps'] * 100}
    write_header(os.path.join(project, 'Source', 'SignalUnknown', 'Logic', 'SUManorData.h'), manor, pts, tomb_manifest, tomb_pts, speeds)
    json.dump(manifest, open(os.path.join(work, 'manifest.json'), 'w'), indent=1)
    for k, v in sizes.items():
        print('%-12s %6.2f MB' % (k, v / 1e6))


if __name__ == '__main__':
    main(*sys.argv[1:])
